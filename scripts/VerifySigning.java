import java.io.FileInputStream;
import java.io.IOException;
import java.security.KeyStore;
import java.security.MessageDigest;
import java.security.UnrecoverableKeyException;
import java.util.Arrays;
import java.util.HexFormat;

/**
 * Fails fast before expensive Android builds if the stored signing secrets
 * cannot unlock the actual private key or certificate fingerprint differs.
 * Never prints keystore, passwords or key material.
 */
public class VerifySigning {
    private static String required(String name) {
        String value = System.getenv(name);
        if (value == null || value.isBlank()) {
            throw new IllegalStateException("Missing signing input: " + name);
        }
        return value;
    }

    public static void main(String[] args) throws Exception {
        char[] storePassword = required("ANDROID_KEYSTORE_PASSWORD").toCharArray();
        char[] keyPassword = required("ANDROID_KEY_PASSWORD").toCharArray();
        try {
            KeyStore keystore = KeyStore.getInstance("PKCS12");
            try (FileInputStream input = new FileInputStream(required("ANDROID_SIGNING_KEYSTORE_PATH"))) {
                try {
                    keystore.load(input, storePassword);
                } catch (IOException cause) {
                    throw new IllegalStateException(
                        "KEYSTORE_PASSWORD_INVALID_OR_CORRUPT: check ANDROID_KEYSTORE_PASSWORD and keystore backup.");
                }
            }
            String alias = required("ANDROID_KEY_ALIAS");
            if (!keystore.containsAlias(alias) || !keystore.isKeyEntry(alias)) {
                throw new IllegalStateException("KEY_ALIAS_INVALID: check ANDROID_KEY_ALIAS.");
            }
            try {
                if (keystore.getKey(alias, keyPassword) == null) {
                    throw new IllegalStateException("KEY_NOT_FOUND: keystore has no accessible private key.");
                }
            } catch (UnrecoverableKeyException cause) {
                throw new IllegalStateException(
                    "KEY_PASSWORD_INVALID: ANDROID_KEY_PASSWORD cannot unlock the private key. "
                    + "For the PKCS12 keystore generated by Setup-Drift-Signing.ps1, "
                    + "use the SAME password as ANDROID_KEYSTORE_PASSWORD.");
            }
            var certificate = keystore.getCertificate(alias);
            if (certificate == null) {
                throw new IllegalStateException("SIGNING_CERTIFICATE_MISSING");
            }
            String actual = HexFormat.of().formatHex(
                MessageDigest.getInstance("SHA-256").digest(certificate.getEncoded()));
            String expected = required("ANDROID_CERT_SHA256")
                .replace(":", "").replaceAll("\\s+", "").toLowerCase(java.util.Locale.ROOT);
            if (!actual.equals(expected)) {
                throw new IllegalStateException(
                    "CERT_FINGERPRINT_MISMATCH: ANDROID_CERT_SHA256 does not match the saved keystore.");
            }
            System.out.println("SIGNING_KEY_PREFLIGHT_PASS");
        } finally {
            Arrays.fill(storePassword, '\0');
            Arrays.fill(keyPassword, '\0');
        }
    }
}
